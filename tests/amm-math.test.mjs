import assert from 'node:assert/strict';
import {isqrt,swapOut,addLiquidity,removeLiquidity} from './amm-math.mjs';
assert.equal(isqrt(0n),0n);assert.equal(isqrt(81n),9n);assert.equal(isqrt(80n),8n);
const q=swapOut(1000000n,20000000n,1000000000000n,30n);assert.ok(q>0n&&q<1000000000000n);
assert.throws(()=>swapOut(0n,1n,1n));assert.throws(()=>swapOut(1n,0n,1n));assert.throws(()=>swapOut(1n,1n,1n,10000n));
const first=addLiquidity(20000000n,1000000000000n,0n,0n,0n);assert.equal(first.shares,isqrt(20000000n*1000000000000n));
const later=addLiquidity(10000000n,500000000000n,20000000n,1000000000000n,first.shares);assert.ok(later.shares>0n);
assert.throws(()=>addLiquidity(10000000n,700000000000n,20000000n,1000000000000n,first.shares),'ratio mismatch');
const removed=removeLiquidity(first.shares,30000000n,1500000000000n,first.shares+later.shares);assert.ok(removed.tez>0n&&removed.token>0n);
assert.throws(()=>removeLiquidity(0n,1n,1n,1n));assert.throws(()=>removeLiquidity(2n,1n,1n,1n));
console.log('AMM integer reference math tests passed (not on-chain contract tests).');
