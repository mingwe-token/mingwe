import assert from 'node:assert/strict';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
const start=html.indexOf('<script type="module">');
const end=html.indexOf('</script>',start);
assert.ok(start>=0&&end>start,'module script must exist');
const js=html.slice(start+'<script type="module">'.length,end);
const syntax=spawnSync(process.execPath,['--check','--input-type=module'],{input:js,encoding:'utf8'});
assert.equal(syntax.status,0,syntax.stderr||syntax.stdout);
assert.match(js,/async function readXtzBalance\(addr\)/,'direct RPC balance reader must be present');
assert.match(js,/\/v1\/accounts\/\$\{addr\}/,'TzKT fallback must be present');
assert.doesNotMatch(js,/tezos-shadownet\.octez\.io/,'do not use the stale fallback RPC');
console.log('Inline module syntax and XTZ balance-reader checks passed.');
